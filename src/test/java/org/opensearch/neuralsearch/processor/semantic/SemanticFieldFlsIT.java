package org.opensearch.neuralsearch.processor.semantic;

import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Base64;
import java.util.List;
import java.util.Locale;
import java.util.Map;

import org.junit.BeforeClass;
import org.opensearch.client.Request;
import org.opensearch.client.RequestOptions;
import org.opensearch.client.Response;
import org.opensearch.neuralsearch.BaseNeuralSearchIT;

import static org.junit.Assume.assumeTrue;

/** Exercises FLS against companion fields generated by real semantic ingestion. */
public class SemanticFieldFlsIT extends BaseNeuralSearchIT {
    private static final String USER = "semantic_fls_reader";
    private static final String PASSWORD = "SemanticFlsReader1!";

    @BeforeClass
    public static void requireSecurity() {
        assumeTrue("requires the Security plugin", Boolean.parseBoolean(System.getProperty("security.enabled", "false")));
    }

    @SuppressWarnings("unchecked")
    public void testExcludedSemanticFieldHidesGeneratedChunks() throws Exception {
        String modelId = prepareSparseEncodingModel();
        loadAndWaitForModelToBeReady(modelId);
        List<String> exposed = new ArrayList<>();
        try {
            for (String companion : List.of("title_semantic_info", "custom_info")) {
                String index = "semantic-fls-" + companion;
                String custom = companion.equals("custom_info") ? ",\"semantic_info_field_name\":\"custom_info\"" : "";
                request("PUT", "/" + index, String.format(Locale.ROOT, """
                    {"mappings":{"properties":{
                      "title":{"type":"semantic","chunking":true,"model_id":"%s"%s},
                      "public_field":{"type":"keyword"}
                    }}}
                    """, modelId, custom), false);
                ingestDocument(index, "{\"title\":\"The secret bicycle is red.\",\"public_field\":\"visible\"}", "1", false);
                Map<String, Object> adminSource = (Map<String, Object>) responseAsMap(request("GET", "/" + index + "/_doc/1", null, false))
                    .get("_source");
                assertTrue("ingestion must generate the companion", adminSource.containsKey(companion));
                Map<String, Object> generated = (Map<String, Object>) adminSource.get(companion);
                Map<String, Object> firstChunk = ((List<Map<String, Object>>) generated.get("chunks")).get(0);
                assertEquals("The secret bicycle is red.", firstChunk.get("text"));
                assertFalse(((Map<?, ?>) firstChunk.get("embedding")).isEmpty());
                String chunkQuery = String.format(Locale.ROOT, """
                    {"query":{"nested":{"path":"%s.chunks","query":{"match":{"%s.chunks.text":"bicycle"}}}}}
                    """, companion, companion);
                assertEquals(1, getHitCount(responseAsMap(request("POST", "/" + index + "/_search", chunkQuery, false))));

                for (String fls : List.of(
                    "[\"~title\"]",
                    "[\"~title\",\"~" + companion + "\"]",
                    "[\"public_field\"]",
                    "[\"~unrelated\"]"
                )) {
                    request("PUT", "/_plugins/_security/api/roles/" + USER, String.format(Locale.ROOT, """
                        {"index_permissions":[{"index_patterns":["%s"],"allowed_actions":["read"],"fls":%s}]}
                        """, index, fls), false);
                    request("PUT", "/_plugins/_security/api/internalusers/" + USER, "{\"password\":\"" + PASSWORD + "\"}", false);
                    request("PUT", "/_plugins/_security/api/rolesmapping/" + USER, "{\"users\":[\"" + USER + "\"]}", false);
                    Map<String, Object> source = (Map<String, Object>) responseAsMap(request("GET", "/" + index + "/_doc/1", null, true))
                        .get("_source");
                    boolean visible = fls.equals("[\"~unrelated\"]");
                    assertEquals(visible, source.containsKey("title"));
                    assertEquals("visible", source.get("public_field"));
                    Map<String, Object> search = responseAsMap(request("POST", "/" + index + "/_search", chunkQuery, true));
                    assertEquals(0, ((Number) ((Map<?, ?>) search.get("_shards")).get("failed")).intValue());
                    int hits = getHitCount(search);
                    logger.info(
                        "Semantic FLS: companion={}, fls={}, companionVisible={}, chunkQueryHits={}",
                        companion,
                        fls,
                        source.containsKey(companion),
                        hits
                    );
                    if (fls.equals("[\"~title\"]")) {
                        if (source.containsKey(companion) || hits != 0) exposed.add(companion);
                    } else {
                        assertEquals(visible, source.containsKey(companion));
                        assertEquals(visible ? 1 : 0, hits);
                    }
                }
            }
            assertTrue("Excluded semantic fields still expose generated companions: " + exposed, exposed.isEmpty());
        } finally {
            for (String type : List.of("rolesmapping", "internalusers", "roles")) {
                Request delete = new Request("DELETE", "/_plugins/_security/api/" + type + "/" + USER);
                delete.addParameter("ignore", "404");
                client().performRequest(delete);
            }
        }
    }

    private Response request(String method, String path, String body, boolean restricted) throws Exception {
        Request request = new Request(method, path);
        if (body != null) request.setJsonEntity(body);
        if (restricted) {
            request.setOptions(
                RequestOptions.DEFAULT.toBuilder()
                    .addHeader(
                        "Authorization",
                        "Basic " + Base64.getEncoder().encodeToString((USER + ":" + PASSWORD).getBytes(StandardCharsets.UTF_8))
                    )
                    .build()
            );
        }
        return client().performRequest(request);
    }
}
